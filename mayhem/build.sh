#!/usr/bin/env bash
#
# mayhem/build.sh — yabai fuzz harness + functional oracle.
#
# yabai is a macOS-only window manager (Carbon/Cocoa/SkyLight, unity build in src/manifest.m), so
# its upstream build cannot run on Linux. This builds the parts that parse untrusted input — the
# daemon command-socket parser (src/message.c, src/rule.c, src/event_signal.c,
# src/mission_control.c) — as a unity build (mayhem/harnesses/yabai_unity.h) against stand-in
# headers for the Apple frameworks (mayhem/stubs/apple_stubs.h). Every function the parser calls
# outside that unit (the window/space/display managers and the Apple frameworks) is resolved by a
# stub generated here from the linker's undefined-symbol list, returning 0/NULL ("not found").
# The scripting-addition payload (src/osax/payload.m, injected into Dock) is compiled as
# Objective-C with clang's GNUstep-2 ABI against mayhem/stubs/sa; with no Objective-C runtime,
# objc_msgSend is one of those stubs, so every message send returns nil.
set -euo pipefail
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
: "${SRC:=/mayhem}"
: "${STANDALONE_FUZZ_MAIN:?STANDALONE_FUZZ_MAIN must point at the run-once driver (set by the base image)}"

cd "$SRC"
OUT="$SRC/mayhem/build"
mkdir -p "$OUT"

# yabai is written for Apple clang: implicit declarations of Apple calls and loose pointer
# conversions are accepted there; keep them warnings here.
CFLAGS_COMMON="-std=gnu11 -pthread -Imayhem/stubs -Imayhem/harnesses \
  -Wno-implicit-function-declaration -Wno-int-conversion -Wno-incompatible-function-pointer-types \
  -Wno-incompatible-pointer-types -Wno-everything"

# Zero-returning stubs for every symbol still undefined after linking against libc/libpthread.
# $1 = object, $2 = output stub source, $3... = extra link flags
gen_stubs() {
    local obj="$1" stubs="$2"; shift 2
    : > "$stubs"
    local syms
    syms=$($CC "$@" "$obj" -x c /dev/null -lm -pthread -o "$OUT/.linkprobe" 2>&1 \
        | grep -oE "undefined (reference to|symbol:) [\`']?\.?[A-Za-z_][A-Za-z0-9_]*" \
        | grep -oE "\.?[A-Za-z_][A-Za-z0-9_]*$" | LC_ALL=C sort -u || true)
    rm -f "$OUT/.linkprobe"
    {
        echo "/* generated by mayhem/build.sh: macOS framework / non-linked yabai module stubs */"
        for s in $syms; do
            case "$s" in
                # data the code only takes the address of or reads (ObjC class refs, linker
                # section bounds, CF callback tables, Mach globals): zero-filled storage
                .*|__start_*|__stop_*|_NSConcrete*|k[A-Z]*|vm_page_size|mach_task_self_)
                    printf '__asm__(".bss\\n.globl %s\\n.type %s,@object\\n.balign 16\\n%s:\\n.zero 64\\n.size %s,64\\n.text\\n");\n' "$s" "$s" "$s" "$s"
                    continue ;;
            esac
            printf '__asm__(".text\\n.globl %s\\n.type %s,@function\\n%s:\\n xorl %%eax,%%eax\\n xorl %%edx,%%edx\\n pxor %%xmm0,%%xmm0\\n pxor %%xmm1,%%xmm1\\n ret\\n");\n' "$s" "$s" "$s"
        done
    } > "$stubs"
}

# lsan_off: leaks are not the bug class fuzzed here (SPEC §6.2 item 15)
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c mayhem/lsan_off.c -o "$OUT/lsan_off.o"

# 1) fuzz harness (sanitized, DWARF 3), fuzzer + standalone reproducer
$CC $CFLAGS_COMMON $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link \
    -c mayhem/harnesses/fuzz_message.c -o "$OUT/fuzz_message.o"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$OUT/standalone_main.o"
gen_stubs "$OUT/fuzz_message.o" "$OUT/fuzz_stubs.c" $SANITIZER_FLAGS $LIB_FUZZING_ENGINE "$OUT/lsan_off.o"
$CC $DEBUG_FLAGS -c "$OUT/fuzz_stubs.c" -o "$OUT/fuzz_stubs.o"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$OUT/fuzz_message.o" "$OUT/fuzz_stubs.o" \
    "$OUT/lsan_off.o" -lm -pthread -o "$OUT/fuzz_message"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS "$OUT/standalone_main.o" "$OUT/fuzz_message.o" "$OUT/fuzz_stubs.o" \
    "$OUT/lsan_off.o" -lm -pthread -o "$OUT/fuzz_message-standalone"

# 2) scripting-addition payload harness (src/osax/payload.m, Objective-C, GNUstep-2 ABI, no runtime)
OBJCFLAGS="-x objective-c -fobjc-runtime=gnustep-2.0 -fno-objc-arc -fblocks -std=gnu11 -pthread \
  -Imayhem/stubs/sa -Imayhem/stubs -Wno-everything"
$CC $OBJCFLAGS $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link \
    -c mayhem/harnesses/fuzz_sa.m -o "$OUT/fuzz_sa.o"
$CC -Imayhem/stubs $SANITIZER_FLAGS $DEBUG_FLAGS -c mayhem/stubs/sa_skylight.c -o "$OUT/sa_skylight.o"
gen_stubs "$OUT/fuzz_sa.o" "$OUT/sa_stubs.c" $SANITIZER_FLAGS $LIB_FUZZING_ENGINE "$OUT/lsan_off.o" "$OUT/sa_skylight.o"
$CC $DEBUG_FLAGS -c "$OUT/sa_stubs.c" -o "$OUT/sa_stubs.o"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$OUT/fuzz_sa.o" "$OUT/sa_skylight.o" "$OUT/sa_stubs.o" \
    "$OUT/lsan_off.o" -lm -pthread -o "$OUT/fuzz_sa"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS "$OUT/standalone_main.o" "$OUT/fuzz_sa.o" "$OUT/sa_skylight.o" "$OUT/sa_stubs.o" \
    "$OUT/lsan_off.o" -lm -pthread -o "$OUT/fuzz_sa-standalone"

# 3) functional oracle: same parser, normal flags, driven by known messages (mayhem/tests)
$CC $CFLAGS_COMMON -O1 $COVERAGE_FLAGS -c mayhem/tests/message_test.c -o "$OUT/message_test.o"
gen_stubs "$OUT/message_test.o" "$OUT/test_stubs.c" $COVERAGE_FLAGS
$CC -c "$OUT/test_stubs.c" -o "$OUT/test_stubs.o"
$CC $COVERAGE_FLAGS "$OUT/message_test.o" "$OUT/test_stubs.o" -lm -pthread -o "$OUT/message_test"

ls -l "$OUT/fuzz_message" "$OUT/fuzz_message-standalone" "$OUT/fuzz_sa" "$OUT/fuzz_sa-standalone" "$OUT/message_test"
